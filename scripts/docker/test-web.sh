#!/usr/bin/env bash
# The web stack as the container runs it: php-fpm and nginx started by supervise.sh,
# against a stub docroot whose index.php reports which php-fpm pool answered. Checks
# that the rendered nginx.conf follows Drupal's nginx guidance and executes only
# index.php, that the start-up log is clean, that private downloads cannot starve page
# requests, and that SIGTERM stops everything promptly. See docs/docker-build.md,
# "Security hardening" and "Startup, supervision and health".
set -u
source "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

IMAGE=mukurtu-test:image
NAME="mukurtu-web-test-$$"
STUB="$(mktemp -d -t mukurtu-stub.XXXXXX)"
trap 'docker rm -f "$NAME" >/dev/null 2>&1; rm -rf "$STUB" "$BUILD_LOG"' EXIT

if ! runtime_image "$IMAGE"; then
  fail "runtime image builds"; tail -30 "$BUILD_LOG"; finish; exit 1
fi

# Stub docroot. Files that would be dangerous if executed or served exist on
# purpose, so a 404 proves a rule fired rather than that the file was missing.
mkdir -p "$STUB/sites/default/files/css" "$STUB/sites/default/files/styles/thumb/public" "$STUB/core"
cat >"$STUB/index.php" <<'PHP'
<?php
header('X-Pool: ' . getenv('MUKURTU_POOL'));
header('X-Content-Type-Options: nosniff');   // Drupal sets this itself
if (str_contains($_SERVER['REQUEST_URI'] ?? '', 'bigpage')) { echo str_repeat('x', 6000000); }
if (str_contains($_SERVER['REQUEST_URI'] ?? '', 'slow')) { sleep(8); }
echo 'index ' . ($_SERVER['REQUEST_URI'] ?? '') . ' script=' . ($_SERVER['SCRIPT_FILENAME'] ?? '');
PHP
echo '<?php echo "EXECUTED";' >"$STUB/sites/default/files/x.php"
echo '<?php echo "EXECUTED";' >"$STUB/core/install.php"
echo '<?php echo "EXECUTED";' >"$STUB/update.php"
echo '{"name":"x"}' >"$STUB/composer.json"
echo 'secret: yes' >"$STUB/config.yml"
echo 'body{}' >"$STUB/sites/default/files/css/x.css"
echo 'jpeg' >"$STUB/sites/default/files/styles/thumb/public/b.jpg"
chmod -R a+rX "$STUB"

# Started the way the container starts it: render the configuration, then supervise.sh.
# (The entrypoint's database and install steps are covered by test-entrypoint.sh.)
docker run -d --name "$NAME" --entrypoint sh -e MUKURTU_CRON=false -e MUKURTU_FPM_MAX_CHILDREN=2 -e MUKURTU_FPM_FILES_MAX_CHILDREN=2 --tmpfs /tmp/run:size=4m,mode=1777 -v "$STUB:/var/www/html/web:ro" "$IMAGE" -c '
  export MUKURTU_RUN_DIR=/tmp/run
  /usr/local/lib/mukurtu/render-config.sh 2>/dev/null || exit 1
  exec /usr/local/lib/mukurtu/supervise.sh
' >/dev/null

ready=false
for _ in $(seq 1 40); do
  if docker exec "$NAME" curl -sf http://127.0.0.1:8080/healthz >/dev/null 2>&1; then ready=true; break; fi
  sleep 0.25
done
if ! $ready; then
  fail "nginx and php-fpm start"; docker logs "$NAME" 2>&1 | tail -20; finish; exit 1
fi
pass "nginx and php-fpm start"

echo "start-up log"
log="$(docker logs "$NAME" 2>&1)"
assert_contains "$log" "ready to handle connections" "php-fpm reports it is ready"
assert_not_contains "$log" "[alert]" "nginx logs no alert at start-up"
assert_not_contains "$log" "[emerg]" "nginx logs no emergency at start-up"
assert_not_contains "$log" "Permission denied" "nothing is refused permission at start-up"
assert_not_contains "$log" "ERROR" "no error at start-up"

get() { docker exec "$NAME" curl -s -i --max-time 10 "http://127.0.0.1:8080$1"; }
status() { get "$1" | head -1 | awk '{print $2}'; }

echo "routing"
assert_eq "200" "$(status /index.php)" "/index.php is served"
assert_contains "$(get /index.php)" "X-Pool: www" "/index.php goes to the www pool"
assert_contains "$(get /node/1)" "index /node/1" "/node/1 is routed to index.php"
assert_contains "$(get /node/1)" "X-Pool: www" "/node/1 goes to the www pool"
assert_contains "$(get /system/files/a.pdf)" "X-Pool: files" "/system/files/* goes to the files pool"
assert_contains "$(get /system/files/styles/thumb/private/a.jpg)" "X-Pool: files" "private image styles go to the files pool"
assert_contains "$(get /healthz)" "pong" "/healthz is answered by php-fpm ping"
assert_contains "$(get /sites/default/files/styles/thumb/public/a.jpg)" "index /sites/default/files/styles/thumb/public/a.jpg" "a missing image style is generated by Drupal"
assert_contains "$(get /sites/default/files/styles/thumb/public/a.jpg)" "X-Pool: www" "image style generation uses the www pool"

echo "PHP is never executed except index.php"
for path in /sites/default/files/x.php /core/install.php /update.php /vendor/autoload.php /index.php/extra; do
  body="$(get "$path")"
  assert_not_contains "$body" "EXECUTED" "$path does not run"
done
for path in /sites/default/files/x.php /core/install.php /update.php /vendor/autoload.php; do
  assert_eq "404" "$(status "$path")" "$path returns 404"
done

echo "sensitive files are hidden"
for path in /.git/config /.env /composer.json /vendor/autoload.php /config.yml /x.twig /x.module /x.sql; do
  assert_eq "404" "$(status "$path")" "$path returns 404"
done
assert_not_contains "$(get /composer.json)" '"name":"x"' "composer.json content is not served"
assert_not_contains "$(get /config.yml)" "secret: yes" "config.yml content is not served"

echo "headers and caching"
headers="$(get /node/1)"
assert_contains "$headers" "X-Content-Type-Options: nosniff" "nosniff on pages"
assert_contains "$headers" "Referrer-Policy: strict-origin-when-cross-origin" "Referrer-Policy on pages"
assert_not_contains "$headers" "nginx/" "no nginx version in the Server header"
css="$(get /sites/default/files/css/x.css)"
assert_contains "$css" "max-age=31536000" "aggregated CSS is cached for a year"
assert_contains "$css" "X-Content-Type-Options: nosniff" "nosniff is present on cached assets too"
assert_contains "$css" "Referrer-Policy: strict-origin-when-cross-origin" "Referrer-Policy is present on cached assets too"
style="$(get /sites/default/files/styles/thumb/public/b.jpg)"
assert_contains "$style" "max-age=2592000" "image styles are cached for 30 days"
assert_contains "$style" "X-Content-Type-Options: nosniff" "nosniff is present on image styles"

echo "uploads are buffered in the upload temp area, not in the small run directory"
# /tmp/run is a 4 MB tmpfs here, like the 16 MB /run in the Compose examples.
docker exec "$NAME" sh -c 'head -c 20000000 /dev/zero > /tmp/upload.bin'
upload="$(docker exec "$NAME" curl -s -o /dev/null -w '%{http_code}' --max-time 20 --data-binary @/tmp/upload.bin http://127.0.0.1:8080/index.php)"
assert_eq "200" "$upload" "a 20 MB upload succeeds although the run directory holds only 4 MB"

echo "headers are not sent twice, large pages stay in memory, and login tokens are not logged"
count_header() { grep -ci "^$2:" <<<"$1" || true; }
assert_eq "1" "$(count_header "$(get /node/1)" X-Content-Type-Options)" "a PHP response carries X-Content-Type-Options once (Drupal sets it, nginx does not repeat it)"
assert_eq "1" "$(count_header "$(get /sites/default/files/css/x.css)" X-Content-Type-Options)" "a static file carries it once (nginx sets it)"
assert_eq "1" "$(count_header "$(get /node/1)" Referrer-Policy)" "a PHP response carries Referrer-Policy once"
# nginx spills a response to a temporary file when the client reads more slowly than PHP
# writes and the page is bigger than the socket buffers (about 6 MB here). That is good (it
# frees the PHP worker) but nginx logs it at "warn" level together with the request URL,
# which for a login link includes the token. Read a big page slowly, as a real browser
# might (about 4 seconds for 6 MB).
assert_eq "200" "$(docker exec "$NAME" curl -s -o /dev/null -w '%{http_code}' --max-time 30 --limit-rate 1500k http://127.0.0.1:8080/bigpage)" "a 6 MB page is served to a slow client"
assert_not_contains "$(docker logs "$NAME" 2>&1)" "an upstream response is buffered to a temporary file" "the spill to a temporary file is not logged (the log line would carry the URL)"
docker exec "$NAME" curl -s -o /dev/null --max-time 10 -H 'Referer: http://localhost:8080/user/reset/1/1700000000/REFERERSECRET/login' http://127.0.0.1:8080/user/reset/1/1700000000/URLSECRET/login
sleep 1
access_log="$(docker logs "$NAME" 2>&1)"
assert_not_contains "$access_log" "URLSECRET" "a one-time login token in the URL is not written to the log"
assert_not_contains "$access_log" "REFERERSECRET" "nor one in the Referer header"
assert_contains "$access_log" "/user/reset/[redacted]" "the request is still logged, with the token replaced"

echo "private downloads cannot starve page requests"
# Three slow downloads: two hold the files pool's workers, one waits.
for i in 1 2 3; do
  docker exec -d "$NAME" curl -s -o /dev/null --max-time 20 "http://127.0.0.1:8080/system/files/slow-$i"
done
sleep 1
started=$SECONDS
page="$(docker exec "$NAME" curl -s -o /dev/null -w '%{http_code}' --max-time 4 http://127.0.0.1:8080/node/1)"
assert_eq "200" "$page" "a page request is answered while private downloads are running"
[[ $((SECONDS - started)) -lt 4 ]] && pass "and it is answered promptly" || fail "and it is answered promptly"

echo "cron: the first run comes soon after start, then every interval"
# Run cron.sh with stand-ins for sleep and drush that record what they were asked, so the
# timing can be checked without waiting for it.
cron_run() { # cron_run <interval>: prints the sleep lengths in order, one per line
  docker run --rm --entrypoint sh -e MUKURTU_CRON_INTERVAL="$1" "$IMAGE" -c '
    mkdir -p /tmp/bin
    printf "#!/bin/sh\necho \"\$1\" >> /tmp/sleeps\nexec /bin/busybox sleep 0.05\n" > /tmp/bin/sleep
    printf "#!/bin/sh\necho run >> /tmp/runs\n" > /tmp/bin/drush
    chmod +x /tmp/bin/*
    PATH=/tmp/bin:$PATH timeout 2 /usr/local/lib/mukurtu/cron.sh >/dev/null 2>&1
    cat /tmp/sleeps' 2>&1
}
sleeps="$(cron_run 3600)"
first="$(sed -n 1p <<<"$sleeps")"
[[ "$first" =~ ^[0-9]+$ && "$first" -ge 60 && "$first" -le 90 ]] && pass "with a 3600 s interval the first run waits about a minute ($first s), not an hour" || fail "with a 3600 s interval the first run waits about a minute (got '$first')"
assert_eq "3600" "$(sed -n 2p <<<"$sleeps")" "and the runs after that wait the full interval"
sleeps="$(cron_run 5)"
assert_eq "5" "$(sed -n 1p <<<"$sleeps")" "an interval shorter than a minute is used from the start"

echo "shutdown"
start=$SECONDS
docker stop -t 10 "$NAME" >/dev/null
[[ $((SECONDS - start)) -lt 10 ]] && pass "stops within 10 seconds" || fail "stops within 10 seconds"
assert_eq "0" "$(docker inspect -f '{{.State.ExitCode}}' "$NAME")" "exits 0 on SIGTERM"

finish
